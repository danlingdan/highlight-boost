(async () => {
  const checks = [], runtimeErrors = [];
  window.__hbChecks = checks;
  window.addEventListener('error', event => runtimeErrors.push(event.error?.stack ?? event.message));
  const assert = (name, value, details) => {
    if (!value) throw new Error(`${name}: ${JSON.stringify(details)}`);
    checks.push({ name, passed: true });
  };
  const tick = () => new Promise(resolve => setTimeout(resolve, 150));
  const until = async predicate => { for (let i = 0; i < 40 && !predicate(); i++) await tick(); return predicate(); };
  await app.plugins.loadManifests();
  await app.plugins.setEnable(true);
  await app.plugins.enablePlugin('highlight-boost');
  const plugin = app.plugins.plugins['highlight-boost'];
  const original = structuredClone(plugin.settings);
  plugin.getPreset('important').name = '核心观点';
  plugin.getPreset('important').color = 'yellow';
  plugin.getPreset('question').color = 'red';
  await plugin.saveSettings();
  const source = '# 正文语义\n\nalpha beta gamma\n\n第二段 **强调**\n\n> 引用内容\n\n| 字段 |\n| --- |\n| 表格值 |\n';
  const path = '正文语义.md', old = app.vault.getFileByPath(path);
  const file = old ? (await app.vault.modify(old, source), old) : await app.vault.create(path, source);
  const leaf = app.workspace.getLeaf(false);
  await leaf.openFile(file);
  app.workspace.setActiveLeaf(leaf, { focus: true });
  await leaf.setViewState({ type: 'markdown', state: { file: path, mode: 'source', source: false } });
  const view = leaf.view, editor = view.editor;
  const select = (from, to = from) => editor.setSelection(editor.offsetToPos(from), editor.offsetToPos(to));
  const metadata = () => [...editor.getValue().matchAll(/%%hbp:(.+?)%%/g)].map(match => JSON.parse(match[1]));
  const visible = () => editor.getValue().replace(/%%hbp:.+?%%/g, '');
  let at = source.indexOf('alpha');
  select(at, at + 16);
  app.commands.executeCommandById('highlight-boost:apply-important');
  const first = editor.getValue(), id = metadata()[0].id;
  assert('prose-semantic-snapshot', metadata()[0].semantic === 'important' && metadata()[0].label === '核心观点');
  assert('prose-selection-retained', editor.getSelection() === 'alpha beta gamma');
  app.commands.executeCommandById('highlight-boost:apply-important');
  assert('prose-repeat-keeps-source-and-id', editor.getValue() === first && metadata()[0].id === id);
  at = editor.getValue().indexOf('beta');
  select(at, at + 4);
  app.commands.executeCommandById('highlight-boost:apply-question');
  const split = editor.getValue();
  assert('prose-split-selection-retained', editor.getSelection() === 'beta');
  assert('prose-split-ownership', metadata().map(item => item.semantic).join(',') === 'important,question,important');
  assert('prose-split-identities', new Set(metadata().map(item => item.id)).size === 3);
  editor.undo(); assert('prose-split-single-undo', editor.getValue() === first);
  editor.redo(); assert('prose-split-redo', editor.getValue() === split);
  const questionId = metadata()[1].id;
  at = editor.getValue().indexOf('beta');
  select(at, at + 4);
  app.commands.executeCommandById('highlight-boost:color-purple');
  const colored = editor.getValue();
  assert('prose-color-keeps-semantic', metadata()[1].id === questionId && metadata()[1].semantic === 'question' && metadata()[1].label === '疑问');
  assert('prose-native-color-changes', visible().includes('==🟣beta=='));
  const selectionBeforeRemove = editor.getSelection();
  app.commands.executeCommandById('highlight-boost:remove');
  assert('prose-remove-keeps-outer-ownership', metadata().length === 2 && metadata().every(item => item.semantic === 'important') && visible().includes('==🟡alpha== beta ==🟡gamma=='), { selectionBeforeRemove, visible: visible(), metadata: metadata() });
  editor.undo(); assert('prose-remove-single-undo', editor.getValue() === colored);
  at = editor.getValue().indexOf('alpha');
  select(at, editor.getValue().lastIndexOf('gamma') + 5);
  app.commands.executeCommandById('highlight-boost:apply-action');
  assert('prose-merge-semantic', metadata().length === 1 && metadata()[0].semantic === 'action' && visible().includes('==🟢alpha beta gamma=='));
  at = editor.getValue().indexOf('第二段');
  select(at, at + '第二段 **强调**'.length);
  app.commands.executeCommandById('highlight-boost:apply-important');
  const beforeRename = editor.getValue();
  plugin.getPreset('important').name = '改名以后';
  plugin.getPreset('question').color = 'yellow';
  await plugin.saveSettings();
  assert('prose-preset-rename-keeps-existing-snapshot', editor.getValue() === beforeRename && metadata()[1].semantic === 'important' && metadata()[1].label === '核心观点');
  at = editor.getValue().indexOf('引用内容');
  select(at, at + 4);
  app.commands.executeCommandById('highlight-boost:apply-question');
  at = editor.getValue().indexOf('表格值');
  select(at, at + 3);
  app.commands.executeCommandById('highlight-boost:apply-important');
  assert('prose-table-async-commit', await until(() => metadata().length === 4));
  assert('prose-new-mark-uses-renamed-preset', metadata()[3].label === '改名以后' && metadata()[3].semantic === 'important');
  const saved = editor.getValue();
  await plugin.openPanel();
  const cards = [...document.querySelectorAll('.hb-card')];
  assert('prose-sidebar-semantic-identities', cards.map(card => card.dataset.hbSemantic).join(',') === 'action,important,question,important');
  assert('prose-sidebar-snapshot-label', cards.some(card => card.textContent.includes('核心观点')));
  cards[1].querySelector('.hb-quote').click();
  assert('prose-sidebar-source-jump', editor.getSelection() === '第二段 **强调**');
  await leaf.setViewState({ type: 'markdown', state: { file: path, mode: 'source', source: true } });
  assert('prose-source-raw-metadata', !view.containerEl.querySelector('.hb-metadata-chip'));
  await leaf.setViewState({ type: 'markdown', state: { file: path, mode: 'source', source: false } });
  select(0);
  assert('prose-live-metadata-folding', await until(() => [...view.containerEl.querySelectorAll('.hb-metadata-chip')].some(chip => chip.textContent === '正文标注')));
  const chip = [...view.containerEl.querySelectorAll('.hb-metadata-chip')].find(chip => chip.textContent === '正文标注');
  chip.dispatchEvent(new KeyboardEvent('keydown', { key: 'Enter', bubbles: true }));
  assert('prose-metadata-keyboard-expand', editor.getSelection().startsWith('%%hbp:'));
  await app.vault.modify(file, saved);
  await leaf.setViewState({ type: 'markdown', state: { file: path, mode: 'preview' } });
  const root = view.containerEl.querySelector('.markdown-preview-view');
  assert('prose-reading-native-highlights', await until(() => root.querySelectorAll('mark').length === 4));
  assert('prose-reading-metadata-hidden', !root.textContent.includes('%%hbp:') && !root.textContent.includes('核心观点'));
  assert('prose-reading-inline-markdown', root.querySelector('mark strong')?.textContent === '强调');
  assert('prose-reading-keeps-source', await app.vault.read(file) === saved);
  plugin.settings = original;
  await plugin.saveSettings();
  await app.vault.adapter.write(`${app.vault.configDir}/hb-prose-expected.json`, JSON.stringify({ text: saved, ids: metadata().map(item => item.id) }));
  await tick();
  assert('prose-no-runtime-errors', runtimeErrors.length === 0, runtimeErrors);
  return checks;
})()
