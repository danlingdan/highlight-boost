(async () => {
  const checks = [];
  window.__hbChecks = checks;
  const assert = (name, value, details) => {
    if (!value) throw new Error(`${name}: ${JSON.stringify(details)}`);
    checks.push({ name, passed: true });
  };
  const tick = () => new Promise(resolve=>setTimeout(resolve, 150));
  await app.plugins.loadManifests();
  await app.plugins.setEnable(true);
  await app.plugins.enablePlugin('highlight-boost');
  const long = `const message = "${'word '.repeat(160)}";`;
  const source = `# 长行布局\n\n\`\`\`js\n${long}\nshort();\n\n\`\`\`\n`;
  const old = app.vault.getFileByPath('布局验证.md');
  const file = old ? (await app.vault.modify(old, source), old) : await app.vault.create('布局验证.md', source);
  const leaf = app.workspace.getLeaf(false);
  await leaf.openFile(file);
  app.workspace.setActiveLeaf(leaf, { focus: true });
  await leaf.setViewState({ type: 'markdown', state: { file: file.path, mode: 'source', source: false } });
  const view = leaf.view, editor = view.editor;
  let at = source.indexOf('word');
  editor.setSelection(editor.offsetToPos(at), editor.offsetToPos(at + 200));
  app.commands.executeCommandById('highlight-boost:apply-question');
  at = editor.getValue().lastIndexOf('const message');
  editor.setCursor(editor.offsetToPos(at));
  app.commands.executeCommandById('highlight-boost:lines-important');
  await tick();
  const line = view.containerEl.querySelector('.cm-line.hb-line');
  const content = view.containerEl.querySelector('.cm-content');
  assert('editor-full-line-background', line.getBoundingClientRect().width > 0 && line.getBoundingClientRect().width >= content.getBoundingClientRect().width - 20);
  const saved = editor.getValue();
  await app.vault.modify(file, saved);
  await leaf.setViewState({ type: 'markdown', state: { file: file.path, mode: 'preview' } });
  const root = view.containerEl.querySelector('.markdown-preview-view');
  for (let i = 0; i < 40 && !root.querySelector('pre .hb-code-row.hb-line'); i++) await tick();
  root.classList.add('hb-layout-test');
  const style = document.createElement('style');
  style.textContent = '.hb-layout-test pre { white-space: pre-wrap; overflow-wrap: anywhere } .hb-layout-test pre > code { white-space: pre-wrap }';
  document.head.append(style);
  await tick();
  const code = root.querySelector('pre code'), pre = code.parentElement;
  const row = code.querySelector('.hb-code-row.hb-line');
  assert('reading-line-background', getComputedStyle(row).backgroundColor !== 'rgba(0, 0, 0, 0)');
  const original = code.textContent;
  const width = row.getBoundingClientRect().width;
  const available = pre.clientWidth - parseFloat(getComputedStyle(pre).paddingLeft) - parseFloat(getComputedStyle(pre).paddingRight);
  assert('reading-full-line-background', width > 0 && width >= available - 2 && width <= available + 2, { width, available });
  const height = row.getBoundingClientRect().height;
  const short = code.querySelectorAll('.hb-code-row')[1].getBoundingClientRect().height;
  assert('reading-soft-wrap', height > short * 2, { height, short });
  assert('text-highlight-crosses-wraps', code.querySelector('.hb-text').getClientRects().length > 1);
  assert('layout-keeps-code-text', code.textContent === original && original === `${long}\nshort();\n\n`);
  assert('layout-keeps-source', await app.vault.read(file) === saved);
  style.remove();
  return checks;
})()
