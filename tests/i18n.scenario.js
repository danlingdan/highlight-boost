(async () => {
  const checks = [], runtimeErrors = [];
  window.__hbChecks = checks;
  window.addEventListener('error', event => runtimeErrors.push(event.error?.stack ?? event.message));
  const assert = (name, value, details) => { if (!value) throw new Error(`${name}: ${JSON.stringify(details)}`); checks.push({ name, passed: true }); };
  const tick = () => new Promise(resolve => setTimeout(resolve, 150));
  const until = async predicate => { for (let i = 0; i < 40 && !predicate(); i++) await tick(); return predicate(); };
  await app.plugins.loadManifests();
  await app.plugins.setEnable(true);
  await app.plugins.enablePlugin('highlight-boost');
  let plugin = app.plugins.plugins['highlight-boost'];
  const originalSettings = structuredClone(plugin.settings);
  plugin.settings.language = 'zh';
  await plugin.saveSettings();
  const code = 'const value = 1;\nconsole.log(value);\nconsole.log(value + 1);';
  const source = `# Language\n\nProse \`inline()\`.\n\n==🔴legacy==\n\nFresh custom\n\n\`\`\`js collapse={2-3}\n${code}\n\`\`\`\n`;
  const path = '语言验证.md', old = app.vault.getFileByPath(path);
  const file = old ? (await app.vault.modify(old, source), old) : await app.vault.create(path, source);
  const leaf = app.workspace.getLeaf(false);
  await leaf.openFile(file);
  app.workspace.setActiveLeaf(leaf, { focus: true });
  await leaf.setViewState({ type: 'markdown', state: { file: path, mode: 'source', source: false } });
  const view = leaf.view, editor = view.editor;
  const mark = (word, command) => {
    const at = editor.getValue().lastIndexOf(word);
    editor.setSelection(editor.offsetToPos(at), editor.offsetToPos(at + word.length));
    app.commands.executeCommandById(`highlight-boost:${command}`);
  };
  mark('Prose', 'apply-important');
  mark('inline()', 'apply-question');
  mark('value =', 'apply-action');
  const saved = editor.getValue(), configured = JSON.stringify(plugin.settings.presets);
  await plugin.openPanel('note');
  assert('zh-sidebar-title', document.querySelector('.hb-panel h4').textContent === '高亮工作台');
  app.setting.open();
  app.setting.openTabById('highlight-boost');
  await tick();
  const tab = app.setting.pluginTabs.find(tab => tab.id === 'highlight-boost');
  const language = tab.containerEl.querySelector('[data-hb-setting="language"]');
  language.value = 'en';
  language.dispatchEvent(new Event('change', { bubbles: true }));
  assert('language-control-updates-settings', await until(() => plugin.settings.language === 'en' && tab.containerEl.textContent.includes('Interface language')));
  await plugin.settingsWrites;
  assert('english-commands-update', app.commands.commands['highlight-boost:apply-important'].name === `${plugin.manifest.name}: Mark as Important`);
  assert('english-color-and-static-commands', app.commands.commands['highlight-boost:color-purple'].name.endsWith('Highlight color: Purple') && app.commands.commands['highlight-boost:remove'].name.endsWith('Remove selected annotations'));
  assert('english-default-preset-display', tab.containerEl.querySelector('[data-hb-preset="important"]').value === 'Important');
  assert('language-keeps-configured-names', JSON.stringify(plugin.settings.presets) === configured);
  assert('language-keeps-note-snapshots', editor.getValue() === saved);
  assert('english-sidebar-title', document.querySelector('.hb-panel h4').textContent === 'Highlight workbench');
  const sidebarLeaf = app.workspace.getLeavesOfType('highlight-boost')[0];
  assert('english-sidebar-tab-title', await until(() => sidebarLeaf.tabHeaderEl.textContent.includes('Highlight workbench')), sidebarLeaf.tabHeaderEl.outerHTML);
  assert('english-sidebar-content-labels', document.querySelector('.hb-panel').textContent.includes('Inline code') && document.querySelector('.hb-panel').textContent.includes('重点'));
  assert('english-legacy-color-label', [...document.querySelectorAll('.hb-card')].some(card => card.querySelector('.hb-quote').textContent === 'legacy' && card.querySelector('.hb-semantic').textContent === 'Red' && card.querySelector('.hb-type').textContent === 'Prose'));
  assert('english-metadata-labels', await until(() => [...view.containerEl.querySelectorAll('.hb-metadata-chip')].some(chip => chip.textContent === 'Prose annotation')));
  assert('english-metadata-accessibility', [...view.containerEl.querySelectorAll('.hb-metadata-chip')].every(chip => chip.getAttribute('aria-label') === 'Expand annotation metadata'));
  assert('english-setting-accessibility', tab.containerEl.querySelector('[data-hb-preset="important"]').getAttribute('aria-label') === 'Important name');
  const customInput = tab.containerEl.querySelector('[data-hb-preset="important"]');
  customInput.value = '重点';
  customInput.dispatchEvent(new Event('input', { bubbles: true }));
  await plugin.settingsWrites;
  assert('same-as-default-name-can-be-custom', plugin.getPreset('important').customName === true && plugin.presetLabel(plugin.getPreset('important')) === '重点');
  assert('custom-name-command-updates', app.commands.commands['highlight-boost:apply-important'].name.endsWith('Mark as 重点'));
  app.setting.close();
  app.workspace.setActiveLeaf(leaf, { focus: true });
  editor.focus();
  app.commands.executeCommandById('highlight-boost:choose-color');
  const picker = [...plugin.colorPickers][0];
  assert('english-picker-placeholder', picker.inputEl.placeholder === 'Choose highlight color');
  assert('bilingual-color-search', picker.getSuggestions('紫').includes('purple') && picker.getSuggestions('BLUE').includes('blue'));
  assert('english-picker-render', await until(() => picker.modalEl.textContent.includes('Purple')));
  plugin.settings.language = 'zh';
  await plugin.saveSettings();
  assert('open-picker-switches-language', picker.inputEl.placeholder === '选择高亮颜色' && await until(() => picker.modalEl.textContent.includes('紫色')));
  assert('custom-name-keeps-original-text', plugin.getPreset('important').name === '重点' && plugin.getPreset('important').customName === true);
  picker.close();
  assert('picker-closes-cleanly', plugin.colorPickers.size === 0);
  plugin.settings.language = 'en';
  await plugin.saveSettings();
  editor.setCursor({ line: 0, ch: 0 });
  app.commands.executeCommandById('highlight-boost:remove');
  assert('english-empty-selection-notice', await until(() => [...document.querySelectorAll('.notice')].some(notice => notice.textContent.includes('Select text or place the cursor'))));
  const inside = editor.getValue().lastIndexOf('value =');
  editor.setCursor(editor.offsetToPos(inside));
  app.commands.executeCommandById('highlight-boost:apply-important');
  assert('english-core-editing-notice', await until(() => [...document.querySelectorAll('.notice')].some(notice => notice.textContent.includes('Select the code text to mark.'))));
  assert('switching-and-notices-keep-source', editor.getValue() === saved);
  mark('Fresh', 'apply-reference');
  mark('custom', 'apply-important');
  const marked = editor.getValue();
  const metadata = [...marked.matchAll(/%%(?:hbp|hbi):(.+?)%%/g)].map(match => JSON.parse(match[1]));
  assert('new-default-annotation-uses-english-name', metadata.some(item => item.semantic === 'reference' && item.label === 'Reference'));
  assert('custom-annotation-keeps-custom-name', metadata.filter(item => item.semantic === 'important').every(item => item.label === '重点'));
  await app.vault.modify(file, marked);
  plugin.settings.syntaxProvider = 'shiki';
  await plugin.saveSettings();
  await app.plugins.disablePlugin('highlight-boost');
  await app.plugins.enablePlugin('highlight-boost');
  plugin = app.plugins.plugins['highlight-boost'];
  await leaf.setViewState({ type: 'markdown', state: { file: path, mode: 'preview' } });
  const copy = () => view.containerEl.querySelector('.markdown-preview-view .hb-syntax-render .copy button');
  assert('builtin-code-english-tooltip', await until(() => copy()?.title === 'Copy to clipboard'));
  const copyData = copy().dataset.code;
  assert('builtin-code-english-collapse', view.containerEl.querySelector('.markdown-preview-view').textContent.includes('2 collapsed lines'));
  plugin.settings.language = 'zh';
  await plugin.saveSettings();
  assert('builtin-code-tooltip-updates-live', await until(() => copy()?.title === '复制到剪贴板' && copy().dataset.copied === '已复制！'));
  assert('builtin-code-collapse-updates-live', view.containerEl.querySelector('.markdown-preview-view').textContent.includes('已折叠 2 行'));
  assert('builtin-code-copy-data-kept', copy().dataset.code === copyData);
  plugin.settings.language = 'auto';
  await plugin.saveSettings();
  assert('auto-language-setting-persists', (await plugin.loadData()).language === 'auto');
  plugin.settings.language = 'en';
  await plugin.saveSettings();
  assert('language-switch-keeps-saved-note', await app.vault.read(file) === marked);
  await app.vault.adapter.write(`${app.vault.configDir}/hb-i18n-expected.json`, JSON.stringify({ source: marked, originalSettings }));
  await tick();
  assert('i18n-no-runtime-errors', runtimeErrors.length === 0, runtimeErrors);
  return checks;
})()
