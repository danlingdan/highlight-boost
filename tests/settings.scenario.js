(async () => {
  const checks = [];
  window.__hbChecks = checks;
  const assert = (name, value) => {
    if (!value) throw new Error(name);
    checks.push({ name, passed: true });
  };
  await app.plugins.loadManifests();
  await app.plugins.setEnable(true);
  await app.plugins.enablePlugin('highlight-boost');
  let plugin = app.plugins.plugins['highlight-boost'];
  const original = structuredClone(plugin.settings);
  await plugin.saveData({ schemaVersion: 1, defaultPreset: 'question' });
  await app.plugins.disablePlugin('highlight-boost');
  await app.plugins.enablePlugin('highlight-boost');
  plugin = app.plugins.plugins['highlight-boost'];
  assert('legacy-settings-migrate', plugin.settings.schemaVersion === 2 && plugin.settings.defaultPreset === 'question');
  assert('migration-persists', (await plugin.loadData()).schemaVersion === 2);
  plugin.getPreset('important').name = '考点';
  plugin.getPreset('important').color = 'purple';
  plugin.settings.defaultPreset = 'important';
  await plugin.saveSettings();
  assert('command-name-updates', app.commands.commands['highlight-boost:apply-important'].name.includes('考点'));
  assert('line-command-name-updates', app.commands.commands['highlight-boost:lines-important'].name.includes('考点'));
  const path = '配置验证.md', source = '正文考点\n\n```js\nconst target = 7;\n```\n';
  const old = app.vault.getFileByPath(path);
  const file = old ? (await app.vault.modify(old, source), old) : await app.vault.create(path, source);
  const leaf = app.workspace.getLeaf(false);
  await leaf.openFile(file);
  await leaf.setViewState({ type: 'markdown', state: { file: path, mode: 'source', source: false } });
  const editor = leaf.view.editor;
  editor.setSelection(editor.offsetToPos(0), editor.offsetToPos(4));
  app.commands.executeCommandById('highlight-boost:apply-important');
  assert('preset-color-applies-to-prose', editor.getValue().startsWith('==🟣正文考点=='));
  const at = editor.getValue().indexOf('target');
  editor.setSelection(editor.offsetToPos(at), editor.offsetToPos(at + 6));
  app.commands.executeCommandById('highlight-boost:apply-important');
  const metadata = () => JSON.parse(editor.getValue().match(/%%hb:(.+)%%/)[1]);
  assert('preset-snapshot-applies-to-code', metadata().marks[0].semantic === 'important' && metadata().marks[0].label === '考点' && metadata().marks[0].color === 'purple');
  const marked = editor.getValue();
  plugin.getPreset('important').name = '关键点';
  plugin.getPreset('important').color = 'blue';
  await plugin.saveSettings();
  assert('preset-edit-keeps-existing-mark', editor.getValue() === marked && metadata().marks[0].label === '考点');
  const writes = [];
  for (const name of ['甲', '乙', '最终名称']) {
    plugin.getPreset('important').name = name;
    writes.push(plugin.saveSettings());
  }
  await Promise.all(writes);
  assert('queued-writes-keep-latest-setting', (await plugin.loadData()).presets[0].name === '最终名称');
  await app.plugins.disablePlugin('highlight-boost');
  await app.plugins.enablePlugin('highlight-boost');
  plugin = app.plugins.plugins['highlight-boost'];
  assert('custom-presets-reload', plugin.getPreset('important').name === '最终名称' && plugin.getPreset('important').color === 'blue');
  assert('default-preset-reloads', plugin.defaultPreset().id === 'important');
  app.setting.open();
  app.setting.openTabById('highlight-boost');
  await new Promise(resolve => setTimeout(resolve, 150));
  const tab = app.setting.pluginTabs.find(tab => tab.id === 'highlight-boost');
  const inputs = [...tab.containerEl.querySelectorAll('input')].filter(input => input.type === 'text');
  assert(`settings-controls-render (${inputs.length})`, inputs.length === 4);
  inputs[0].value = '界面修改';
  inputs[0].dispatchEvent(new Event('input', { bubbles: true }));
  await plugin.settingsWrites;
  assert('settings-input-persists', (await plugin.loadData()).presets[0].name === '界面修改');
  const reset = [...tab.containerEl.querySelectorAll('button')].find(button => button.textContent === '恢复默认');
  reset.click();
  await plugin.settingsWrites;
  assert('settings-reset-restores-defaults', plugin.getPreset('important').name === '重点' && plugin.getPreset('important').color === 'yellow');
  app.setting.close();
  plugin.settings = original;
  await plugin.saveSettings();
  assert('original-settings-restored', JSON.stringify(plugin.settings) === JSON.stringify(original));
  return checks;
})()
