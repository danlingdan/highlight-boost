(async () => {
  const checks = [], errors = []; window.__hbChecks = checks;
  const tick = () => new Promise(resolve => setTimeout(resolve, 100));
  const activate = leaf => app.workspace.setActiveLeaf(leaf, { focus: true });
  const until = async predicate => { for (let i = 0; i < 60 && !predicate(); i++) await tick(); return predicate(); };
  const assert = (name, value, details) => { if (!value) throw new Error(`${name}: ${JSON.stringify(details)}`); checks.push({ name, passed: true }); };
  let phase = 'open'; const events = [];
  const observe = event => { errors.push(event.message); events.push({ phase, message: event.message }); };
  window.addEventListener('error', observe);
  await app.plugins.loadManifests(); await app.plugins.setEnable(true); await app.plugins.enablePlugin('highlight-boost');
  const plugin = app.plugins.plugins['highlight-boost'], original = structuredClone(plugin.settings);
  plugin.settings.language = 'zh'; plugin.settings.selectionToolbar = true; await plugin.saveSettings();
  const path = '窗口批注融合.md', text = '# Window actions\n\nlocal text\n';
  const old = app.vault.getFileByPath(path), file = old ? (await app.vault.modify(old, text), old) : await app.vault.create(path, text);
  const duplicate = app.workspace.getLeaf('tab'); await duplicate.openFile(file);
  const leaf = app.workspace.getLeaf('tab'); await leaf.openFile(file);
  await leaf.setViewState({ type: 'markdown', state: { file: path, mode: 'source', source: true } });
  const popout = app.workspace.moveLeafToPopout(leaf, { width: 900, height: 700 });
  assert('actions-real-popout', await until(() => popout.doc?.body && popout.win.__hbPopoutReady));
  popout.win.addEventListener('error', observe); activate(leaf);
  const editor = leaf.view.editor, from = editor.getValue().indexOf('local text');
  editor.focus(); editor.setSelection(editor.offsetToPos(from), editor.offsetToPos(from + 10));
  plugin.apply(editor, plugin.presetForAction('important'));
  const marked = editor.getValue();
  for (const toolbar of plugin.toolbars) if (toolbar.matches(editor)) toolbar.open();
  assert('actions-toolbar-ready', await until(() => popout.doc.querySelector('[data-hb-action="annotation"]')));
  phase = 'open-modal'; popout.doc.querySelector('[data-hb-action="annotation"]').click();
  assert('actions-note-owned-by-source-window', await until(() => popout.doc.querySelector('.hb-note-input')) && !document.querySelector('.hb-note-input'));
  const input = popout.doc.querySelector('.hb-note-input'); input.value = 'popout-undo-note';
  phase = 'save-modal'; [...input.closest('.modal').querySelectorAll('button')].find(button => button.textContent === '保存').click();
  assert('actions-note-saved', await until(() => !input.isConnected && editor.getValue().includes('popout-undo-note')));
  assert('actions-toolbar-continues-after-modal', await until(() => popout.doc.querySelector('[data-hb-action="collection"]')));
  const annotated = editor.getValue(); phase = 'undo'; editor.undo(); await tick();
  assert('actions-undo-in-trigger-editor', editor.getValue() === marked);
  phase = 'redo'; editor.redo(); await tick(); assert('actions-redo-note', editor.getValue() === annotated);
  phase = 'save-file'; await leaf.view.save();
  assert('actions-duplicate-synchronized', await until(() => duplicate.view.editor.getValue() === annotated));
  await tick();
  phase = 'close'; const sourceDoc = popout.doc, sourceWindow = popout.win; sourceWindow.electronWindow.close();
  assert('actions-window-closed', await until(() => sourceWindow.closed));
  assert('actions-runtime-released', await until(() => !plugin.syntax.runtime.documents.has(sourceDoc)));
  assert('actions-toolbar-released', ![...plugin.toolbars].some(toolbar => toolbar.matches(editor)));
  assert('actions-source-preserved', await app.vault.read(file) === annotated);
  phase = 'restore-settings'; plugin.settings = original; await plugin.saveSettings();
  window.__hbObservations = { errors, events }; assert('actions-no-unexpected-page-errors', errors.length === 0, events); return checks;
})()
