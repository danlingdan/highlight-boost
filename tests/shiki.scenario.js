(async () => {
  const checks = [];
  window.__hbChecks = checks;
  const assert = (name, value, details) => {
    if (!value) throw new Error(`${name}: ${JSON.stringify(details)}`);
    checks.push({ name, passed: true });
  };
  const tick = () => new Promise(resolve=>setTimeout(resolve, 150));
  await app.plugins.loadManifests();
  await app.plugins.setEnable(true);
  await app.plugins.enablePlugin('highlight-boost');
  await app.plugins.enablePlugin('shiki-highlighter');
  const shiki = app.plugins.plugins['shiki-highlighter'];
  assert('shiki-load', shiki?.manifest.version === '0.8.0');
  const source = '# Shiki 协作\n\n```js\nconst count = 1;\nconsole.log(count);\n```\n';
  const old = app.vault.getFileByPath('Shiki验证.md');
  const file = old ? (await app.vault.modify(old, source), old) : await app.vault.create('Shiki验证.md', source);
  const leaf = app.workspace.getLeaf(false);
  await leaf.openFile(file);
  await leaf.setViewState({ type: 'markdown', state: { file: file.path, mode: 'source', source: false } });
  const view = leaf.view, editor = view.editor;
  let at = editor.getValue().indexOf('count');
  editor.setSelection(editor.offsetToPos(at), editor.offsetToPos(at + 5));
  app.commands.executeCommandById('highlight-boost:apply-important');
  at = editor.getValue().lastIndexOf('console');
  editor.setSelection(editor.offsetToPos(at), editor.offsetToPos(at + 7));
  app.commands.executeCommandById('highlight-boost:lines-question');
  await tick();
  assert('shiki-editor-text-mark', Boolean(view.containerEl.querySelector('.hb-text')));
  assert('shiki-editor-line-mark', Boolean(view.containerEl.querySelector('.hb-line')));
  const saved = editor.getValue();
  await app.vault.modify(file, saved);
  await leaf.setViewState({ type: 'markdown', state: { file: file.path, mode: 'preview' } });
  app.workspace.setActiveLeaf(leaf, { focus: true });
  for (let i = 0; i < 50 && !view.containerEl.querySelector('.expressive-code'); i++) await tick();
  let output = view.containerEl.querySelector('.expressive-code');
  assert('shiki-reading-render', Boolean(output));
  for (let i = 0; i < 30 && !output.querySelector('.hb-text'); i++) await tick();
  assert('shiki-reading-text-mark', Boolean(output.querySelector('.hb-text')), output.outerHTML.slice(0, 5000));
  assert('shiki-reading-line-mark', Boolean(output.querySelector('.hb-line')));
  const lineBackground = getComputedStyle(output.querySelector('.hb-line')).backgroundColor;
  assert('shiki-line-background-visible', lineBackground !== 'transparent' && lineBackground !== 'rgba(0, 0, 0, 0)');
  assert('shiki-native-row-structure', output.querySelectorAll('.ec-line').length === 2 && !output.querySelector('.hb-code-row'));
  const textMark = output.querySelector('.hb-text');
  assert('shiki-token-color-preserved', getComputedStyle(textMark).color === getComputedStyle(textMark.parentElement).color);
  const expectedCode = 'const count = 1;\nconsole.log(count);';
  assert('shiki-copy-data-preserved', output.querySelector('.copy button')?.dataset.code.replaceAll('\x7f', '\n') === expectedCode);
  for (const block of [...(shiki.activeCodeBlocks.get(file.path) ?? [])]) await block.forceRerender();
  for (let i = 0; i < 40 && !view.containerEl.querySelector('.expressive-code .hb-text'); i++) await tick();
  output = view.containerEl.querySelector('.expressive-code');
  assert('shiki-rerender-restores-marks', Boolean(output.querySelector('.hb-text')) && Boolean(output.querySelector('.hb-line')));
  await app.plugins.disablePlugin('highlight-boost');
  for (let i = 0; i < 40 && !view.containerEl.querySelector('.expressive-code'); i++) await tick();
  output = view.containerEl.querySelector('.expressive-code');
  assert('shiki-unload-cleans-marks', Boolean(output) && !output.querySelector('.hb-text, .hb-line') && output.querySelectorAll('.ec-line').length === 2);
  await app.plugins.enablePlugin('highlight-boost');
  await leaf.setViewState({ type: 'markdown', state: { file: file.path, mode: 'source', source: false } });
  await leaf.setViewState({ type: 'markdown', state: { file: file.path, mode: 'preview' } });
  for (let i = 0; i < 40 && !view.containerEl.querySelector('.expressive-code .hb-text'); i++) await tick();
  assert('shiki-first-load-order', Boolean(view.containerEl.querySelector('.expressive-code .hb-text')));
  assert('shiki-source-unchanged', await app.vault.read(file) === saved);
  return checks;
})()
