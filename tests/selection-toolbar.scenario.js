(async () => {
  const checks = [], errors = [];
  window.__hbChecks = checks;
  window.addEventListener('error', event => errors.push(event.error?.stack ?? event.message));
  const assert = (name, value, details) => { if (!value) throw new Error(`${name}: ${JSON.stringify(details)}`); checks.push({ name, passed: true }); };
  const tick = () => new Promise(resolve => setTimeout(resolve, 120));
  const until = async predicate => { for (let i = 0; i < 35 && !predicate(); i++) await tick(); return predicate(); };
  await app.plugins.loadManifests(); await app.plugins.setEnable(true); await app.plugins.enablePlugin('highlight-boost');
  const plugin = app.plugins.plugins['highlight-boost'], original = structuredClone(plugin.settings);
  plugin.settings.language = 'zh'; plugin.settings.selectionToolbar = true; plugin.settings.recentColors = [];
  await plugin.saveSettings();
  const source = '# 选区面板\n\nalpha beta gamma\n\nInline `inline()` here.\n\n```js\nconst first = 1;\nconst second = 2;\n```\n';
  const path = '选区面板.md', old = app.vault.getFileByPath(path);
  const file = old ? (await app.vault.modify(old, source), old) : await app.vault.create(path, source);
  const leaf = app.workspace.getLeaf(false); await leaf.openFile(file);
  app.workspace.setActiveLeaf(leaf, { focus: true });
  await leaf.setViewState({ type: 'markdown', state: { file: path, mode: 'source', source: true } });
  const view = leaf.view, editor = view.editor;
  const toolbar = () => document.querySelector('.hb-selection-toolbar');
  const select = word => {
    editor.focus(); const from = editor.getValue().lastIndexOf(word);
    editor.setSelection(editor.offsetToPos(from), editor.offsetToPos(from + word.length));
  };
  const click = async action => {
    assert(`toolbar-action-${action}`, await until(() => toolbar()?.querySelector(`[data-hb-action="${action}"]`)));
    const button = toolbar().querySelector(`[data-hb-action="${action}"]`);
    button.dispatchEvent(new PointerEvent('pointerdown', { bubbles: true, cancelable: true, button: 0 })); button.click(); await tick();
  };
  const prose = () => [...editor.getValue().matchAll(/%%hbp:(.+?)%%/g)].map(match => JSON.parse(match[1]));
  const inline = () => [...editor.getValue().matchAll(/%%hbi:(.+?)%%/g)].map(match => JSON.parse(match[1]));
  const code = () => [...editor.getValue().matchAll(/%%hb:(.+?)%%/g)].map(match => JSON.parse(match[1]));
  select('alpha');
  assert('toolbar-auto-opens', await until(() => toolbar()?.textContent.includes('正文')));
  assert('toolbar-accessible', toolbar().getAttribute('role') === 'toolbar' && [...toolbar().querySelectorAll('button')].every(button => button.getAttribute('aria-label')));
  await plugin.openPanel('note'); editor.focus(); select('alpha');
  await click('preset-important');
  assert('toolbar-marks-prose', prose()[0]?.semantic === 'important' && editor.getSelection() === 'alpha');
  assert('sidebar-follows-toolbar-edit', document.querySelectorAll('.hb-card').length === 1);
  await click('palette'); await click('color-purple');
  assert('toolbar-recolor-retains-semantics-selection', prose()[0]?.semantic === 'important' && editor.getSelection() === 'alpha' && editor.getValue().includes('==🟣alpha=='));
  assert('toolbar-recent-color', await until(() => toolbar()?.querySelector('[data-hb-action="recent-purple"]')));
  const marked = editor.getValue(); editor.undo();
  assert('toolbar-color-single-undo', !editor.getValue().includes('==🟣alpha==') && prose().length === 1);
  editor.redo(); assert('toolbar-color-redo', editor.getValue() === marked);
  select('inline()'); await click('preset-question');
  assert('toolbar-inline-whole-token', inline()[0]?.semantic === 'question' && editor.getValue().includes('`inline()`'));
  select('first');
  assert('toolbar-code-context', await until(() => toolbar()?.textContent.includes('代码块 1 · 第 1—1 行')));
  await click('mode-lines');
  assert('toolbar-line-mode-selected', await until(() => toolbar()?.querySelector('[data-hb-action="mode-lines"]')?.getAttribute('aria-pressed') === 'true'));
  await click('preset-action');
  assert('toolbar-marks-whole-line', code()[0]?.marks[0]?.kind === 'lines' && code()[0].marks[0].quote === 'const first = 1;');
  await until(() => toolbar()?.querySelector('[data-hb-action="mode-lines"]')?.getAttribute('aria-pressed') === 'true');
  await window.require('electron').ipcRenderer.invoke('hb-selection-capture', 'selection-dark-zh');
  select('second'); await click('preset-reference');
  assert('toolbar-new-selection-defaults-text', code()[0]?.marks.some(mark => mark.kind === 'text' && mark.quote === 'second'));
  const codeBefore = editor.getValue().match(/```js\n([\s\S]*?)\n```/)[1];
  await click('remove');
  assert('toolbar-remove-keeps-other-code-mark', code()[0].marks.length === 1 && code()[0].marks[0].semantic === 'action');
  assert('toolbar-code-source-exact', editor.getValue().match(/```js\n([\s\S]*?)\n```/)[1] === codeBefore);
  select('beta');
  assert('toolbar-prose-context-ready', await until(() => toolbar()?.querySelector('.hb-selection-context')?.textContent.includes('正文') && !toolbar().querySelector('[data-hb-action="mode-text"]')));
  toolbar().querySelector('button').focus();
  toolbar().dispatchEvent(new KeyboardEvent('keydown', { key: 'ArrowRight', bubbles: true, cancelable: true }));
  assert('toolbar-arrow-navigation', document.activeElement?.dataset.hbAction === 'preset-question');
  document.activeElement.dispatchEvent(new KeyboardEvent('keydown', { key: 'End', bubbles: true, cancelable: true }));
  assert('toolbar-end-navigation', document.activeElement?.dataset.hbAction === 'close');
  document.activeElement.dispatchEvent(new KeyboardEvent('keydown', { key: 'Escape', bubbles: true, cancelable: true }));
  await tick(); assert('toolbar-escape-closes', !toolbar());
  editor.setSelection({ line: 0, ch: 0 });
  plugin.settings.selectionToolbar = false; await plugin.saveSettings(); select('gamma'); await tick();
  assert('toolbar-setting-disables-auto', !toolbar());
  app.commands.executeCommandById('highlight-boost:selection-toolbar');
  assert('toolbar-command-opens-when-auto-off', await until(() => toolbar()));
  document.body.dispatchEvent(new PointerEvent('pointerdown', { bubbles: true })); await tick();
  assert('toolbar-outside-closes', !toolbar());
  plugin.settings.selectionToolbar = true; await plugin.saveSettings(); select('beta');
  await until(() => toolbar());
  const beforeLanguage = editor.getValue(); plugin.settings.language = 'en'; await plugin.saveSettings();
  assert('toolbar-language-switch', await until(() => toolbar()?.getAttribute('aria-label') === 'Selection toolbar' && toolbar().textContent.includes('Important')));
  assert('toolbar-language-keeps-note', editor.getValue() === beforeLanguage);
  editor.cm.contentDOM.dispatchEvent(new CompositionEvent('compositionstart', { bubbles: true })); await tick();
  assert('toolbar-hidden-during-composition', !toolbar());
  editor.cm.contentDOM.dispatchEvent(new CompositionEvent('compositionend', { bubbles: true })); await tick();
  await plugin.openPanel('note');
  const panel = document.querySelector('.hb-panel'), search = panel.querySelector('.hb-search');
  search.value = 'inline'; search.dispatchEvent(new Event('input', { bubbles: true }));
  assert('sidebar-search-filters', panel.querySelectorAll('.hb-card').length === 1 && panel.querySelector('.hb-card').textContent.includes('inline()'));
  assert('sidebar-search-control-retained', search === panel.querySelector('.hb-search'));
  search.value = ''; search.dispatchEvent(new Event('input', { bubbles: true }));
  const type = panel.querySelector('.hb-type-filter'); type.value = 'code'; type.dispatchEvent(new Event('change', { bubbles: true }));
  assert('sidebar-code-filter', panel.querySelectorAll('.hb-card').length === 1 && panel.querySelector('.hb-card').textContent.includes('const first'));
  const semantic = panel.querySelector('.hb-semantic-filter'); semantic.value = 'question'; semantic.dispatchEvent(new Event('change', { bubbles: true }));
  assert('sidebar-combined-filters-empty-state', panel.querySelectorAll('.hb-card').length === 0 && panel.textContent.includes('No matching highlights'));
  semantic.value = ''; semantic.dispatchEvent(new Event('change', { bubbles: true }));
  window.__hbUI.menu(panel.querySelector('.hb-card-more'), plugin.t('changeSemantic') + ' · ' + plugin.presetLabel(plugin.getPreset('reference'))).click();
  assert('sidebar-changes-code-semantic', code()[0].marks[0].semantic === 'reference');
  const beforeRemove = editor.getValue(); window.__hbUI.menu(panel.querySelector('.hb-card-more'), plugin.t('removeItem')).click();
  assert('sidebar-removes-single-code-mark', code().length === 0 && prose().length === 1 && inline().length === 1);
  editor.undo(); assert('sidebar-remove-single-undo', editor.getValue() === beforeRemove);
  type.value = ''; type.dispatchEvent(new Event('change', { bubbles: true }));
  const proseCard = [...panel.querySelectorAll('.hb-card')].find(card => card.querySelector('.hb-quote').textContent === 'alpha');
  window.__hbUI.menu(proseCard.querySelector('.hb-card-more'), plugin.t('changeSemantic') + ' · ' + plugin.presetLabel(plugin.getPreset('action'))).click();
  assert('sidebar-prose-edit-applies-preset', prose()[0].semantic === 'action' && editor.getValue().includes('==🟢alpha=='));
  const inlineCard = [...panel.querySelectorAll('.hb-card')].find(card => card.querySelector('.hb-quote').textContent === 'inline()');
  window.__hbUI.menu(inlineCard.querySelector('.hb-card-more'), plugin.t('removeItem')).click();
  assert('sidebar-inline-remove-keeps-source', inline().length === 0 && editor.getValue().includes('`inline()`'));
  editor.undo();
  app.workspace.setActiveLeaf(leaf, { focus: true }); editor.focus();
  const positions = ['beta', 'gamma'].map(word => {
    const at = editor.getValue().lastIndexOf(word); return { anchor: editor.offsetToPos(at), head: editor.offsetToPos(at + word.length) };
  });
  editor.setSelections(positions);
  assert('toolbar-disjoint-selection-context', await until(() => toolbar()?.textContent.includes('2 selections')));
  const beforeMulti = editor.getValue(); await click('preset-question');
  assert('toolbar-disjoint-selection-transaction', prose().filter(mark => mark.semantic === 'question').length === 2 && editor.listSelections().length === 2);
  editor.undo(); assert('toolbar-disjoint-single-undo', editor.getValue() === beforeMulti);
  select('first'); await click('mode-lines');
  assert('toolbar-line-color-mode-ready', await until(() => toolbar()?.querySelector('[data-hb-action="mode-lines"]')?.getAttribute('aria-pressed') === 'true'));
  await click('color-blue');
  assert('toolbar-line-color-keeps-kind-semantic', code()[0].marks.some(mark => mark.quote === 'const first = 1;' && mark.kind === 'lines' && mark.color === 'blue' && mark.semantic === 'reference'));
  await leaf.setViewState({ type: 'markdown', state: { file: path, mode: 'source', source: false } });
  select('gamma');
  assert('toolbar-live-preview-opens', await until(() => toolbar()?.textContent.includes('Prose')));
  await click('preset-reference');
  assert('toolbar-live-preview-semantic', prose().some(mark => mark.semantic === 'reference') && editor.getSelection() === 'gamma');
  await until(() => toolbar()?.textContent.includes('Prose'));
  const dark = document.body.classList.contains('theme-dark');
  document.body.classList.remove('theme-dark'); document.body.classList.add('theme-light'); await tick();
  await window.require('electron').ipcRenderer.invoke('hb-selection-capture', 'selection-light-en');
  document.body.classList.toggle('theme-dark', dark); document.body.classList.toggle('theme-light', !dark);
  await leaf.setViewState({ type: 'markdown', state: { file: path, mode: 'preview' } }); await tick();
  assert('toolbar-reading-view-cleans-editor-ui', !toolbar());
  await leaf.setViewState({ type: 'markdown', state: { file: path, mode: 'source', source: true } }); editor.focus();
  const selectionSnapshot = editor.getValue(); editor.setValue('one two three');
  select('one'); plugin.apply(editor, plugin.presetForAction('important')); select('three'); plugin.apply(editor, plugin.presetForAction('question'));
  const wholeFrom = editor.getValue().indexOf('one'), wholeTo = editor.getValue().lastIndexOf('three') + 5;
  editor.setSelection(editor.offsetToPos(wholeFrom), editor.offsetToPos(wholeTo)); app.commands.executeCommandById('highlight-boost:selection-toolbar'); await click('preset-reference');
  assert('toolbar-disjoint-existing-marks-keep-bulk-selection', !document.querySelector('.hb-target-option') && plugin.documentFor(editor).items.every(item => item.semantic === 'reference'));
  editor.setValue(selectionSnapshot);
  const savedSettings = await plugin.loadData();
  assert('toolbar-recent-colors-persist', savedSettings.recentColors.join(',') === 'blue,purple');
  plugin.settings.selectionToolbar = false; await plugin.saveSettings();
  await app.plugins.disablePlugin('highlight-boost');
  assert('toolbar-unload-cleans-dom', !toolbar() && plugin.toolbars.size === 0);
  await app.plugins.enablePlugin('highlight-boost');
  const restored = app.plugins.plugins['highlight-boost'];
  assert('toolbar-setting-and-recents-reload', restored.settings.selectionToolbar === false && restored.settings.recentColors.join(',') === 'blue,purple');
  restored.settings = original; await restored.saveSettings();
  assert('toolbar-settings-restore', JSON.stringify(restored.settings) === JSON.stringify(original));
  assert('toolbar-no-page-errors', errors.length === 0, errors);
  return checks;
})()
