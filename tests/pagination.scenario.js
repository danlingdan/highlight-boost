(async () => {
  const checks = []; window.__hbChecks = checks;
  const assert = (name, value) => { if (!value) throw new Error(name); checks.push({ name, passed: true }); };
  const tick = () => new Promise(resolve => setTimeout(resolve, 120));
  await app.plugins.loadManifests(); await app.plugins.setEnable(true); await app.plugins.enablePlugin('highlight-boost');
  const plugin = app.plugins.plugins['highlight-boost'], original = structuredClone(plugin.settings);
  plugin.settings.language = 'zh'; await plugin.saveSettings();
  const path = '分页验收.md', text = '# 分页\n\n' + Array.from({ length: 123 }, (_, i) => `==item-${String(i).padStart(3, '0')}==`).join('\n\n');
  const existing = app.vault.getFileByPath(path), file = existing ? (await app.vault.modify(existing, text), existing) : await app.vault.create(path, text);
  const leaf = app.workspace.getLeaf(false); await leaf.openFile(file); app.workspace.setActiveLeaf(leaf, { focus: true });
  await plugin.index.enqueue(path); await plugin.openPanel('note');
  let workbench = app.workspace.getLeavesOfType('highlight-boost')[0].view;
  const panel = () => workbench.contentEl, cards = () => [...panel().querySelectorAll('.hb-card')];
  const turn = direction => panel().querySelector(`[data-hb-page="${direction}"]`).click();
  const set = (key, value) => { const input = panel().querySelector(`.hb-${key}`); input.value = value; input.dispatchEvent(new Event(input.tagName === 'INPUT' ? 'input' : 'change', { bubbles: true })); };
  const first = () => cards()[0]?.querySelector('.hb-quote').textContent;
  assert('pagination-first-page-bounded', cards().length === 50 && first() === 'item-000');
  assert('pagination-full-summary', panel().querySelector('.hb-summary').textContent.includes('123'));
  assert('pagination-controls-labelled', panel().querySelector('.hb-pagination').getAttribute('aria-label') === '结果分页' && panel().querySelector('.hb-pagination [role="status"]').textContent.includes('1—50/123'));
  assert('pagination-previous-disabled', panel().querySelector('[data-hb-page="previous"]').disabled);
  turn('next'); assert('pagination-second-page', cards().length === 50 && first() === 'item-050');
  assert('pagination-focus-after-turn', document.activeElement?.dataset.hbPage === 'next');
  workbench.refresh(); assert('pagination-refresh-keeps-page', first() === 'item-050');
  const retainedCard = cards()[0], retainedNext = panel().querySelector('[data-hb-page="next"]'), retainedOption = panel().querySelector('.hb-sort option');
  retainedNext.focus(); workbench.refresh();
  assert('pagination-unchanged-card-retained', cards()[0] === retainedCard);
  assert('pagination-progress-retains-focus', document.activeElement === retainedNext && panel().querySelector('[data-hb-page="next"]') === retainedNext);
  assert('pagination-unchanged-options-retained', panel().querySelector('.hb-sort option') === retainedOption);
  const state = workbench.getState(); assert('pagination-state-saves-page', state.page === 1);
  await workbench.leaf.setViewState({ type: 'highlight-boost', state });
  assert('pagination-state-restores-page', first() === 'item-050');
  turn('next'); assert('pagination-last-page', cards().length === 23 && first() === 'item-100' && panel().querySelector('[data-hb-page="next"]').disabled);
  turn('previous'); assert('pagination-previous-order', first() === 'item-050');
  set('search', 'item-12'); assert('pagination-filter-resets-page', cards().length === 3 && first() === 'item-120' && !panel().querySelector('.hb-pagination'));
  set('search', 'missing-result'); assert('pagination-empty-no-controls', cards().length === 0 && !panel().querySelector('.hb-pagination'));
  set('search', ''); assert('pagination-clear-filter-starts-first', first() === 'item-000');
  turn('next'); set('sort', 'semantic'); assert('pagination-sort-resets-page', first() === 'item-000');
  turn('next'); await workbench.setScope('folder'); assert('pagination-scope-resets-page', workbench.getState().page === 0);
  set('sort', 'source'); set('path-filter', path); await workbench.setScope('vault'); turn('next');
  assert('pagination-group-heading-on-page', panel().querySelector('.hb-result-group').textContent === path);
  plugin.settings.language = 'en'; await plugin.saveSettings();
  assert('pagination-language-keeps-page', first() === 'item-050' && panel().querySelector('.hb-pagination').getAttribute('aria-label') === 'Result pages');
  assert('pagination-english-status', panel().querySelector('.hb-pagination [role="status"]').textContent === 'Page 2/3 · 51–100 of 123');
  await window.require('electron').ipcRenderer.invoke('hb-selection-capture', 'workbench-pagination');
  let exported;
  const exportHits = plugin.exportExcerpt.bind(plugin);
  plugin.exportExcerpt = async hits => { assert('pagination-export-all-hits', hits.includes('item-000') && hits.includes('item-122')); exported = await exportHits(hits); return exported; };
  window.__hbUI.export(panel());
  for (let i = 0; i < 50 && !exported; i++) await tick();
  const exportText = exported && await app.vault.read(exported);
  assert('pagination-export-first-last', exportText?.includes('item-000') && exportText.includes('item-122'));
  plugin.exportExcerpt = exportHits;
  const entries = plugin.index.notes.get(path).items.map(item => ({ id: crypto.randomUUID(), path, kind: item.kind, from: item.from, quote: item.quote, prefix: '', suffix: '', color: item.color, label: item.label }));
  plugin.settings.collections.push({ id: 'pagination-full', name: 'Full pages', entries }, { id: 'pagination-part', name: 'Partial pages', entries: entries.slice(60).map(entry => ({ ...entry, id: crypto.randomUUID() })) });
  await plugin.saveSettings(); set('collection', 'pagination-full'); await workbench.setScope('collection'); turn('next');
  assert('pagination-collection-second-page', workbench.getState().page === 1);
  set('collection', 'pagination-part');
  assert('pagination-collection-change-resets-page', workbench.getState().page === 0 && first() === 'item-060');
  await leaf.openFile(file); app.workspace.setActiveLeaf(leaf, { focus: true });
  await workbench.setScope('note'); turn('next'); turn('next');
  leaf.view.editor.setValue('# Short\n\n==only-one=='); await plugin.index.ready; workbench.refresh();
  assert('pagination-removal-clamps-page', cards().length === 1 && first() === 'only-one' && workbench.getState().page === 0);
  leaf.view.editor.setValue(text); await plugin.index.ready; workbench.refresh();
  await workbench.leaf.setViewState({ type: 'highlight-boost', state: { scope: 'note', page: Number.MAX_SAFE_INTEGER } });
  assert('pagination-restored-page-clamped', cards().length === 23 && first() === 'item-100');
  await workbench.leaf.setViewState({ type: 'highlight-boost', state: { scope: 'note', page: -1 } });
  assert('pagination-invalid-page-first', first() === 'item-000');
  await app.vault.modify(file, text); if (exported) await app.vault.delete(exported);
  plugin.settings = original; await plugin.saveSettings();
  await app.plugins.disablePlugin('highlight-boost');
  assert('pagination-unload-removes-controls', !document.querySelector('.hb-pagination'));
  await app.plugins.enablePlugin('highlight-boost');
  return checks;
})()
