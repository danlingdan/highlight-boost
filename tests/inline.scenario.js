(async () => {
  const checks = [];
  const runtimeErrors = [];
  window.addEventListener('error', event => runtimeErrors.push(event.error?.stack ?? event.message));
  window.__hbChecks = checks;
  const assert = (name, condition, details) => {
    if (!condition) throw new Error(`${name}: ${JSON.stringify(details)}`);
    checks.push({ name, passed: true });
  };
  const tick = () => new Promise(resolve => setTimeout(resolve, 150));
  const until = async predicate => { for (let i = 0; i < 40 && !predicate(); i++) await tick(); return predicate(); };
  await app.plugins.loadManifests();
  await app.plugins.setEnable(true);
  await app.plugins.enablePlugin('highlight-boost');
  let plugin = app.plugins.plugins['highlight-boost'];
  const originalSyntax = plugin.settings.syntaxProvider;
  const originalLanguage = plugin.settings.language;
  plugin.settings.language = 'zh';
  await plugin.saveSettings();
  const source = '# 行内验证\n\n前文 `a==b` 后文\n\n第一次 `same`，第二次 `same`。\n\n复杂 `` a`b ``\n\n> 引用 `one`\n\n跨行 `multi\nline`\n\n| 字段 |\n| --- |\n| `value` |\n';
  const path = '行内验证.md', old = app.vault.getFileByPath(path);
  const file = old ? (await app.vault.modify(old, source), old) : await app.vault.create(path, source);
  const leaf = app.workspace.getLeaf(false);
  await leaf.openFile(file);
  app.workspace.setActiveLeaf(leaf, { focus: true });
  await leaf.setViewState({ type: 'markdown', state: { file: path, mode: 'source', source: false } });
  const view = leaf.view, editor = view.editor;
  const select = (from, to = from) => editor.setSelection(editor.offsetToPos(from), editor.offsetToPos(to));
  let at = source.indexOf('a==b');
  select(at, at + 1);
  app.commands.executeCommandById('highlight-boost:apply-important');
  const first = editor.getValue();
  assert('inline-code-characters-preserved', first.includes('`a==b`%%hbi:') && first.includes('"semantic":"important"'));
  assert('partial-selection-preserved', editor.getSelection() === 'a');
  assert('inline-live-decoration', await until(() => [...view.containerEl.querySelectorAll('.hb-inline')].some(node => node.textContent === 'a==b')));
  editor.undo(); assert('inline-single-undo', editor.getValue() === source);
  editor.redo(); assert('inline-redo', editor.getValue() === first);
  select(editor.getValue().indexOf('a==b') + 1);
  app.commands.executeCommandById('highlight-boost:apply-question');
  assert('inline-cursor-recolors', editor.getValue().includes('"color":"red"') && (editor.getValue().match(/%%hbi:/g) ?? []).length === 1);
  app.commands.executeCommandById('highlight-boost:remove');
  assert('inline-remove-restores-source', editor.getValue() === source);
  select(source.indexOf('前文'), source.indexOf('后文') + 2);
  app.commands.executeCommandById('highlight-boost:apply-reference');
  assert('inline-mixed-prose-transaction', editor.getValue().replace(/%%hbp:.+?%%/g, '').includes('==🔵前文== `a==b`%%hbi:') && editor.getValue().includes('==🔵后文=='));
  editor.undo(); assert('inline-mixed-single-undo', editor.getValue() === source);
  select(source.indexOf('a==b'));
  app.commands.executeCommandById('highlight-boost:apply-question');
  at = editor.getValue().indexOf('same');
  select(at, at + 4);
  app.commands.executeCommandById('highlight-boost:apply-important');
  at = editor.getValue().lastIndexOf('same');
  select(at, at + 4);
  app.commands.executeCommandById('highlight-boost:apply-question');
  at = editor.getValue().indexOf('a`b');
  select(at, at + 3);
  app.commands.executeCommandById('highlight-boost:apply-reference');
  at = editor.getValue().indexOf('`one`') + 1;
  select(at);
  app.commands.executeCommandById('highlight-boost:apply-action');
  at = editor.getValue().indexOf('`multi') + 1;
  select(at, at + 5);
  app.commands.executeCommandById('highlight-boost:apply-reference');
  at = editor.getValue().indexOf('`value`') + 1;
  select(at, at + 5);
  const beforeTable = editor.getValue();
  app.commands.executeCommandById('highlight-boost:apply-action');
  assert('inline-table-syntax-preserved', await until(() => editor.getValue().includes('| `value`%%hbi:')));
  const afterTable = editor.getValue();
  editor.undo(); assert('inline-table-single-undo', editor.getValue() === beforeTable);
  editor.redo(); assert('inline-table-redo', editor.getValue() === afterTable);
  await plugin.openPanel();
  const cards = [...document.querySelectorAll('.hb-card')];
  assert('inline-sidebar-items', cards.length === 7 && cards.every(card => card.textContent.includes('行内代码')));
  assert('inline-sidebar-no-block-rebind', !document.querySelector('.hb-rebind'));
  const complex = cards.find(card => card.querySelector('.hb-quote').textContent === 'a`b');
  complex.querySelector('.hb-quote').click();
  assert('inline-sidebar-source-jump', await until(() => editor.getSelection() === ' a`b '));
  let copied = '';
  const write = navigator.clipboard.writeText;
  navigator.clipboard.writeText = async value => { copied = value; };
  complex.querySelector('.hb-copy-excerpt').click();
  navigator.clipboard.writeText = write;
  assert('inline-excerpt-uses-safe-delimiter', copied.startsWith('``a`b``\n\n来源：') && copied.includes('#行内验证'));
  const saved = editor.getValue();
  await app.vault.modify(file, saved);
  await leaf.setViewState({ type: 'markdown', state: { file: path, mode: 'source', source: true } });
  select(saved.indexOf('a==b'));
  assert('inline-source-decoration', await until(() => Boolean(view.containerEl.querySelector('.hb-inline'))));
  assert('inline-source-metadata-visible', !view.containerEl.querySelector('.hb-metadata-chip'));
  await leaf.setViewState({ type: 'markdown', state: { file: path, mode: 'preview' } });
  const reading = () => view.containerEl.querySelector('.markdown-preview-view');
  assert('inline-reading-count', await until(() => reading().querySelectorAll('code.hb-inline').length === 7), [...reading().querySelectorAll('code')].map(code => ({ text: code.textContent, classes: code.className })));
  const codes = [...reading().querySelectorAll('code.hb-inline')];
  assert('inline-reading-visible-underline', getComputedStyle(codes[0]).boxShadow !== 'none');
  assert('inline-reading-equals-kept', codes.some(code => code.textContent === 'a==b' && code.classList.contains('hb-red')));
  assert('inline-reading-duplicate-colors', codes.filter(code => code.textContent === 'same').map(code => code.classList.contains('hb-red') ? 'red' : 'yellow').join(',') === 'yellow,red');
  assert('inline-reading-backtick-kept', codes.some(code => code.textContent === 'a`b'));
  assert('inline-reading-code-only', reading().querySelectorAll('code').length === 7);
  assert('inline-reading-multiline-normalization', codes.some(code => code.textContent === 'multi line'));
  assert('inline-reading-quote-container', Boolean(reading().querySelector('blockquote code.hb-inline')));
  await app.plugins.disablePlugin('highlight-boost');
  assert('inline-unload-cleanup', !reading().querySelector('.hb-inline'));
  await app.plugins.enablePlugin('highlight-boost');
  plugin = app.plugins.plugins['highlight-boost'];
  await leaf.setViewState({ type: 'markdown', state: { file: path, mode: 'source', source: false } });
  await leaf.setViewState({ type: 'markdown', state: { file: path, mode: 'preview' } });
  assert('inline-reload-restores', await until(() => reading().querySelectorAll('code.hb-inline').length === 7));
  plugin.settings.syntaxProvider = 'shiki';
  await plugin.saveSettings();
  await app.plugins.disablePlugin('highlight-boost');
  await app.plugins.enablePlugin('highlight-boost');
  plugin = app.plugins.plugins['highlight-boost'];
  await leaf.setViewState({ type: 'markdown', state: { file: path, mode: 'source', source: false } });
  await leaf.setViewState({ type: 'markdown', state: { file: path, mode: 'preview' } });
  assert('inline-builtin-syntax-coexists', await until(() => reading().querySelectorAll('code.hb-inline').length === 7));
  plugin.settings.syntaxProvider = originalSyntax;
  plugin.settings.language = originalLanguage;
  await plugin.saveSettings();
  await app.plugins.disablePlugin('highlight-boost');
  await app.plugins.enablePlugin('highlight-boost');
  assert('inline-reading-keeps-source', await app.vault.read(file) === saved);
  await app.vault.adapter.write(`${app.vault.configDir}/hb-inline-expected.json`, JSON.stringify({ text: saved }));
  await tick();
  assert('inline-no-runtime-errors', runtimeErrors.length === 0, runtimeErrors);
  return checks;
})()
